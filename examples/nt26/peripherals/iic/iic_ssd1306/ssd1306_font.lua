--[[ 汉字 CJK：怎么新增（给改字的 AI）

  不要灌整份 GB2312。每加一个字：码点当 key，24 字节点阵当 value。
  ssd1306 :text() 已按 UTF-8 解码，Lua 源码里直接写中文；缺字画 '?'。

  点阵格式（必须按这个写，否则对不齐）
    尺寸 12x12。每字 12 行，每行 2 字节大端，共 24 字节。
    一行里 bit15 = 最左像素 x=0，bit4 = x=11，低 4 bit 不用。
    例：第一行左边 4 个点亮 → 该行 "\xF0\x00"

  生成步骤
    1. 用黑体/宋体栅格化到 12x12 二值图（阈值约 128）。字面可微移 dy=-1 防裁切。
    2. 按行打包：x 从 0 到 11，pixel 亮则 bits |= 1<<(15-x)；写入 hi、lo。
    3. M.CJK[0x码点] = "\x.."  -- 码点 = utf8 解码后的 Unicode，如 「一」= 0x4E00
    4. 全角标点（，U+FF0C）也要单独收录，ASCII 逗号用不了。

  Pillow 示例（本表用 simhei.ttf 12px 生成）：
    from PIL import Image, ImageFont, ImageDraw
    im = Image.new("L", (12, 12), 0)
    ImageDraw.Draw(im).text((0, -1), "字",
        font=ImageFont.truetype("simhei.ttf", 12), fill=255)
    对 y in 0..11、x in 0..11：getpixel>=128 则 bits |= 1<<(15-x)
    每行 append(bits>>8) 和 append(bits&0xFF)，得到 24 字节。
]]
