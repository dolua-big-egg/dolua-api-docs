local rt = require("rt")
-- 注意这个LED不是系统模块，而是我们自己创建的模块 led.lua
local led = require("led")

led.init()

while true do
    -- 演示使用模块内的方法
    led.on()
    -- 演示使用模块内的参数
    rt.delay(led.interval_ms)
    -- 演示使用模块内的方法
    led.off()
    -- 演示使用模块内的参数
    rt.delay(led.interval_ms)
end

--[=[
  module demo — 引用自定义 Lua 模块

  ============================================================================
  自定义模块怎么来
  ============================================================================
  C 扩展（gpio / rt / log）之外，工程里的 .lua 也可以当模块：

    1) 新建文件，例如 led.lua（模块名 = 文件名去掉 .lua）
    2) 在项目的 modules 里登记该文件，才会打进包、可供 require
    3) 文件末尾 return 一张表：里面既放参数，也放方法
    4) 主脚本 local led = require("led") 后，用 led.xxx 访问

  同一模块只会加载一次，多次 require 拿到的是同一张表。

  ============================================================================
  本 demo 的 led 模块
  ============================================================================
  封装开发板指示灯（GPIO 9），主脚本只调方法、不碰 gpio。

    参数  led.PIN           GPIO 编号
          led.interval_ms   闪烁间隔（毫秒）
    方法  led.init()        打开并配成输出（先灭）
          led.on() / off()  亮 / 灭

    模块的最大数量和大小有上限，需根据设备型号而定。

  ============================================================================
  本 demo
  ============================================================================
    1) require("led") 自定义模块
    2) led.init()
    3) 循环 led.on / delay(led.interval_ms) / led.off

]=]
