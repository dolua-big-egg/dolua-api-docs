--[[
  charge demo — CHG_DET 充电状态检测

  ============================================================================
  这不是充电器
  ============================================================================
  模块内部没有充电管理芯片，也不会给电池充电。
  Pin97（CHG_DET）只是一根状态检测脚，用来读外部充电 IC 的 STAT/CHG 脚。
  
]]

local charge = require("charge")
local log = require("log")

local STATUS_CN = {
    [charge.DISCONNECT] = "未接充电器",
    [charge.CHARGING]   = "正在充电",
    [charge.FINISH]     = "充电完成",
}

charge.init()
log.info("[CHARGE] init ok, pin=97 CHG_DET (F6E0, 非 GPIO)")

local last_code = nil

while true do
    local code, name = charge.getstatus()
    local cn = STATUS_CN[code] or "未知"

    if code ~= last_code then
        log.info("[CHARGE] 状态变化 code=%d name=%s 含义=%s", code, name, cn)
        last_code = code
    else
        log.info("[CHARGE] 当前 code=%d name=%s 含义=%s", code, name, cn)
    end

    rt.delay(1000)
end

--[[
  charge demo — CHG_DET 充电状态检测

  ============================================================================
  这不是充电器
  ============================================================================
  模块内部没有充电管理芯片，也不会给电池充电。
  Pin97（CHG_DET）只是一根状态检测脚，用来读外部充电 IC 的 STAT/CHG 脚。

  典型接法：
    USB 5V → 外部充电 IC（VIN）→ BAT → 电池
                    │
                  STAT / CHG / CHRG
                    │
              模块 Pin97  CHG_DET

  ============================================================================
  适配引脚（当前机型 NT26-F6E0）
  ============================================================================
    模块管脚 : Pin97
    信号名   : CHG_DET
    芯片功能 : EC718 Charge Pad（专用充电检测垫，不是普通 GPIO）
    复用     : F6E0 上不与 GPIO 复用，不能用 gpio 模块去配这根脚
    注意     : 不要接到 VBUS / VBAT / CE，只能接充电 IC 的开漏状态脚

  ============================================================================
  检测原理（芯片靠“下拉强度”判断，不是测电压/电流）
  ============================================================================
  Charge Pad 内部可以开关一颗约 10k 上拉，再读脚电平，从而区分三种外部状态：

    1) 先关上拉
         脚为高 / 浮空  → DISCONNECT（没插充电器，STAT 开路）
         脚为低        → 外部有下拉，再做第 2 步
    2) 打开 10k 上拉后再读
         仍然为低      → 强下拉 → CHARGING（正在充电）
         被拉高        → 弱下拉 → FINISH  （充满）

  ============================================================================
  充电 IC 的两种 STAT 风格（对应 charge.h 注释）
  ============================================================================

  【三态 IC】能完整区分三种状态
      强下拉 : CHARGING   正在充电
      弱下拉 : FINISH     充满
      浮空   : DISCONNECT 没接适配器 / 没插 USB

  【两态 IC】只能区分“在充 / 不在充”
      强下拉 : CHARGING
      浮空   : DISCONNECT 或 FINISH（充满和拔掉充电器看起来一样）
      软件把 DISCONNECT 与 FINISH 当成同一类，不要依赖 FINISH=2

  ============================================================================
  常见可对接芯片（STAT/CHG 接到 Pin97）
  ============================================================================
  三态（强下拉 / 弱下拉 / 浮空），可区分充电中、充满、未插充电器：
    LTC4054 / LTC1734
    部分带 3-state CHRG 的线性充芯片（CHRG 在 C/10 时改为弱下拉）

  两态（充电中强下拉，其余浮空），充满和未插充电器无法区分：
    TP4054 / TP4056 / TP4057
    SGM4054 / SGM4056
    LP4054 / LP4056 / ETA4056 等 4056 类克隆
    MCP73831 / MCP73832

  开关充电 IC（STAT 多为开漏两态，同样按两态来用）：
    SGM41511 / BQ25601 / ETA6005
    充电中 STAT 拉低，充满或没插适配器为高阻

  ============================================================================
  Lua 状态码
  ============================================================================
    charge.DISCONNECT = 0  "disconnect"  未接充电器
    charge.CHARGING   = 1  "charging"    正在充电
    charge.FINISH     = 2  "finish"      充电完成（仅三态 IC 可靠）
]]