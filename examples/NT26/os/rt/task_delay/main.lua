--[=[
  rt task/delay demo — 协作式多任务
  ============================================================================
  本 demo
  ============================================================================
    入口协程启动 A、B 两条任务，三条协程各自按不同周期打印。
    观察串口：三条交错出现，说明 delay 让出后调度器在轮流唤醒。

]=]

local rt = require("rt")
local log = require("log")

local function task_a()
    local n = 0
    while true do
        n = n + 1
        log.info("[A] n=%d", n)
        rt.delay(1000)
    end
end

local function task_b()
    local n = 0
    while true do
        n = n + 1
        log.info("[B] n=%d", n)
        rt.delay(1500)
    end
end

--[[ task_start 会立刻执行传入的函数；一碰到 delay 就会让出，
     task_start 随即返回。如果函数里从不让出，会卡在这里。]]
rt.task_start(task_a)
rt.task_start(task_b)

local n = 0
while true do
    n = n + 1
    log.info("[main] n=%d", n)
    rt.delay(2000)
end

--[=[
  rt task/delay demo — 协作式多任务

  脚本里的多任务不是 OS 抢占线程，而是同一 Lua 虚拟机里的协程：
  同一时刻只有一条在跑，遇到 delay / mbox_recv / mq_recv 才切换。

  入口脚本本身也是一条协程，顶层就可以 delay，不必再包一层 task_start。
  入口若死循环且从不 delay，其它任务会被饿死。

  ----------------------------------------------------------------------------
  rt.task_start(fn) -> true
  ----------------------------------------------------------------------------
    立刻开一条协程跑 fn。fn 无参数。资源不足时抛错。
    当前最多 16 条（含入口协程第一次 delay 时占用的那条）。

  ----------------------------------------------------------------------------
  rt.delay(ms)
  ----------------------------------------------------------------------------
    ms > 0   当前协程睡 ms 毫秒（让出）
    ms == -1 无限让出，不设超时
    ms == 0 / 缺参 / 非数字  忽略，不让出
    必须在任务协程里调用，不要在 uart / tmr 回调里 delay。

  ============================================================================
  本 demo
  ============================================================================
    入口启动 A、B，三条协程分别 1s / 1.5s / 2s 打一条日志。

]=]
