--[=[
  helloworld demo — print 基础输出
  ============================================================================
  本 demo
  ============================================================================
    每秒通过 print 向当前 print_route 串口输出 "hello world"。

]=]

local rt = require("rt")

while true do
    print("hello world")
    -- 延时1秒[本质是让出协程一秒]
    rt.delay(1000)
end

--[=[
  helloworld demo — print 基础输出

  ============================================================================
  print 是什么
  ============================================================================
  print 是 Lua 内置全局函数（Lua 5.5 标准库），用于把调试信息输出到控制台。
  在本平台上，输出不会走 PC 终端，而是重定向到模块 UART 串口。

  ============================================================================
  官方 print 支持的功能与特性
  ============================================================================
  1) 可变参数
       print(...)  可传 0 个或多个任意类型参数

  2) 自动转字符串
       每个参数通过 tostring / __tostring 转成字符串后再输出
       常见类型：number、string、boolean、nil、table、userdata 等

  3) 多参分隔
       第 2 个及之后的参数前自动插入制表符 \t
       例：print("a", 1, true)  →  a\t1\ttrue

  4) 自动换行
       每次调用末尾追加 \n，无需手动加换行符

  5) 无返回值
       仅作副作用输出，不返回任何值

  6) 不支持格式化
       print 本身不含 %d / %s 等占位符；需要格式化请用 string.format 或 log 模块

  ============================================================================
  本平台输出重定向（默认 UART1）
  ============================================================================
  底层将 lua_writestring / lua_writeline 重定向到 HAL UART，而非 stdout。

    默认串口 : UART1（print_route = 1）
    可选串口 : UART1 / UART2 / UART3（取值 1 / 2 / 3）
    行结束符 : \n（仅 LF，不带 \r）

  ============================================================================
  修改输出串口
  ============================================================================

  【方式 1】rtu.config 配置文件（推荐，持久生效）
    写入 /rtu.config 的 [lua] 段，脚本启动前自动 apply：

      [lua]
      print_route=1    -- Lua print() 输出串口，1/2/3
      log_route=1      -- log 模块输出串口，1/2/3（与 print 独立）

  【方式 2】Lua 运行时动态切换
    需 require("sys")，立即生效，重启后恢复为配置文件值：

      local sys = require("sys")
      sys.option("print_route", 2)   -- 切到 UART2
      local route = sys.option("print_route")  -- 读取当前路由

  ============================================================================
  与 log 模块的区别（简要）
  ============================================================================
    print          内置、轻量、多参 \t 拼接、无源码位置、无 format
    log.info 等    扩展模块、支持 format / 多参拼接、带文件名行号、可独立路由

  ============================================================================
  本 demo
  ============================================================================
    每秒通过 print 向当前 print_route 串口输出 "hello world"。

]=]
