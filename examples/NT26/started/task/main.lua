--[=[
  task demo — 协作式多任务（协程）
  ============================================================================
  本 demo
  ============================================================================
    入口协程启动 A、B 两条任务，三条协程各自用 log 按不同周期循环打印。
    观察串口：三条交错出现，说明 delay 让出后调度器在轮流唤醒。

]=]

local rt = require("rt")
local log = require("log")

-- 任务A
local function task_a()
    local n = 0
    while true do
        n = n + 1
        log.info("[A] n=%d", n)
        rt.delay(1000)
    end
end

-- 任务B
local function task_b()
    local n = 0
    while true do
        n = n + 1
        log.info("[B] n=%d", n)
        rt.delay(1500)
    end
end

--[[ task_start会立即执行传入的任务，函数里一碰到 delay 等调度方法就会让出，
task_start 随即返回如果传入的任务一直不返回，则会卡在这里，无法执行后面的代码]]
rt.task_start(task_a)
rt.task_start(task_b)

-- 入口协程自己的循环，不必再 task_start
local n = 0
while true do
    n = n + 1
    log.info("[main] n=%d", n)
    rt.delay(2000)
end

--[=[
  task demo — 协作式多任务（协程）

  ============================================================================
  「多线程」在本平台是什么
  ============================================================================
  脚本里的多任务不是操作系统抢占式线程，而是同一 Lua 虚拟机里的多条协程：
  同一时刻只有一条在跑，遇到让出点才切换。看起来像并行，调度是协作式的。

  全局变量、require 的模块、表，所有协程共享同一份。没有进程隔离。

  ============================================================================
  主入口也是一条协程
  ============================================================================
  引擎加载 main.lua 时，不会在「普通函数上下文」里直接跑完它，而是把整份
  入口脚本放进一条独立协程再启动。因此：

    - 文件顶层就可以 rt.delay / 阻塞等待，不必再包一层 task_start
    - 顶层的 while true 和 task_start 出去的循环，地位相同：都是可让出的协程
    - 入口协程若直接 return，只是这条协程结束；其它已启动的任务仍由调度器接着跑
    - 入口若死循环且从不 delay，调度器得不到机会，其它任务会被饿死

  本 demo 里 [main] 那条循环，就是入口协程自己在跑。

  ============================================================================
  调度怎么转起来
  ============================================================================
  1) 启动
       入口协程开始执行 main.lua。
       rt.task_start(fn) 再开一条协程，立刻执行 fn；fn 里一旦 delay，这条
       任务就挂起，task_start 返回，入口继续往下走。

  2) 让出
       rt.delay(ms) 把「当前这条协程」登记一个到期时间，然后让出。
       控制权回到调度器，而不是卡死整台虚拟机。
       同类让出点还有邮箱等待、队列接收等阻塞 API。

  3) 唤醒
       调度器在事件循环里收超时/消息。时间到了，把当初让出的那条协程恢复到
       delay 的下一句，接着跑。

  4) 结束
       协程函数 return，或 while 结束，这条任务被回收。
       全部协程都结束且没有待处理事件时，脚本生命周期结束。

  ============================================================================
  接口
  ============================================================================
    rt.task_start(fn)   启动一条任务协程；fn 是入口函数，无参数
    rt.delay(ms)        当前协程休眠 ms 毫秒（让出）；必须在协程里调用
                        ms=-1 无限让出，不设超时，直到脚本结束

  注意：
    - delay(0) 或非法参数会被忽略，不会让出
    - delay(-1) 无限阻塞：让出当前协程，调度器继续跑其它任务/回调
    - 任务数量有上限（当前最多 16 条，含入口协程第一次 delay 时占用的那条）
    - 不要在回调里 delay（回调不是任务协程）

  ============================================================================
  和「真线程」的差别
  ============================================================================
    抢占式线程   随时可被切走，要锁，数据竞争难查
    本平台协程   只在 delay/等待处切换；两次让出之间的代码互斥执行，
                 一般不用锁。反过来：漏写 delay 的死循环会独占虚拟机。

